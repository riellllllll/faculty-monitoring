/**
 * Build-time font fetcher.
 *
 * Downloads the woff2 subsets we actually use and emits src/styles/fonts.css
 * with the correct unicode-range per subset. Self-hosting is deliberate: the
 * system has to render identically on a lab machine with no network.
 *
 *   node scripts/build-fonts.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const fontDir = resolve(root, 'src/fonts');
const outFile = resolve(root, 'src/styles/fonts.css');

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';

/** Spec-mandated stacks: geometric sans body, editorial serif display, mono for data. */
const FAMILIES = [
  { slug: 'geist',   query: 'Geist:wght@400;500;600;700',      label: 'Geist' },
  { slug: 'mono',    query: 'Geist+Mono:wght@400;500;600',      label: 'Geist Mono' },
  { slug: 'serif',   query: 'Instrument+Serif:ital@0;1',        label: 'Instrument Serif' },
];

mkdirSync(fontDir, { recursive: true });

const blocks = [];
const seen = new Map();

for (const fam of FAMILIES) {
  const css = await (await fetch(
    `https://fonts.googleapis.com/css2?family=${fam.query}&display=swap`,
    { headers: { 'User-Agent': UA } }
  )).text();

  const faces = css.split('@font-face').slice(1);
  for (const face of faces) {
    const src = face.match(/url\((https:[^)]+)\)/);
    const range = face.match(/unicode-range:\s*([^;]+);/);
    const weight = face.match(/font-weight:\s*([^;]+);/);
    const style = face.match(/font-style:\s*([^;]+);/);
    if (!src || !range) continue;

    let file = seen.get(src[1]);
    if (!file) {
      file = `${fam.slug}-${seen.size + 1}.woff2`;
      const buf = Buffer.from(await (await fetch(src[1], { headers: { 'User-Agent': UA } })).arrayBuffer());
      writeFileSync(resolve(fontDir, file), buf);
      seen.set(src[1], file);
    }

    blocks.push(
      `@font-face {\n` +
      `  font-family: '${fam.label}';\n` +
      `  font-style: ${style ? style[1].trim() : 'normal'};\n` +
      `  font-weight: ${weight ? weight[1].trim() : '400 700'};\n` +
      `  font-display: swap;\n` +
      `  src: url('../fonts/${file}') format('woff2');\n` +
      `  unicode-range: ${range[1].trim()};\n` +
      `}`
    );
  }
}

const header =
  `/*\n` +
  `   Self-hosted type. Generated by scripts/build-fonts.mjs -- do not hand-edit.\n\n` +
  `   Geist          utilitarian sans for UI and body copy\n` +
  `   Geist Mono     data, meta-labels, identifiers\n` +
  `   Instrument Serif  editorial display for page titles only\n\n` +
  `   Self-hosted because the system must render offline during a lab defense;\n` +
  `   a CDN link would silently fall back to a system face with no network.\n   */\n\n`;

writeFileSync(outFile, header + blocks.join('\n\n') + '\n', 'utf8');
console.log(`Wrote ${blocks.length} @font-face blocks, ${seen.size} files -> ${outFile}`);
