/**
 * Build-time generator for src/components/icons.js.
 *
 * Extracts inner path data from Phosphor Bold SVGs so the shipped bundle has
 * no runtime dependency on the icon package. Run with:
 *
 *   node scripts/build-icons.mjs
 *
 * Phosphor is used deliberately: the design protocol calls for a thicker,
 * technical glyph weight rather than the thin-line Lucide/Feather family.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const src = resolve(root, 'node_modules/@phosphor-icons/core/assets/bold');
const out = resolve(root, 'src/components/icons.js');

/** Our public name -> Phosphor Bold asset. */
const MAP = {
  // Navigation
  dashboard:      'squares-four',
  users:          'users',
  clipboardCheck: 'clipboard-text',
  chart:          'chart-bar',
  sliders:        'faders',
  logOut:         'sign-out',

  // Brand + actions
  cap:            'graduation-cap',
  search:         'magnifying-glass',
  plus:           'plus',
  check:          'check',
  checkCircle:    'check-circle',
  x:              'x',
  eye:            'eye',
  eyeSlash:       'eye-slash',
  refresh:        'arrows-clockwise',
  download:       'download-simple',
  chevronRight:   'caret-right',
  chevronLeft:    'caret-left',
  caretDown:      'caret-down',
  arrowLeft:      'arrow-left',
  arrowRight:     'arrow-right',

  // Identity + security
  user:           'user',
  lock:           'lock-key',
  shieldCheck:    'shield-check',
  student:        'student',

  // Measurement + rubric
  ruler:          'ruler',
  stack:          'stack',
  target:         'target',
  sealCheck:      'seal-check',
  gauge:          'gauge',

  // Context
  calendar:       'calendar-blank',
  calendarCheck:  'calendar-check',
  clock:          'clock',
  alert:          'warning-circle',
  info:           'info',
  bell:           'bell',
  note:           'note-pencil',
  building:       'buildings',
  fileText:       'file-text',
  trendUp:        'trend-up',
  chalkboard:     'chalkboard-teacher',
  table:          'table',

  // Lists + empty states
  tray:           'tray',
  book:           'book-open',
  funnel:         'funnel-simple',
  sort:           'arrows-down-up',
  dots:           'dots-three-outline',
};

const INNER = /<svg[^>]*>([\s\S]*)<\/svg>/;

const entries = [];
const missing = [];

for (const [name, asset] of Object.entries(MAP)) {
  const file = resolve(src, `${asset}-bold.svg`);
  let raw;
  try {
    raw = readFileSync(file, 'utf8');
  } catch {
    missing.push(`${name} -> ${asset}`);
    continue;
  }
  const m = raw.match(INNER);
  if (!m) {
    missing.push(`${name} -> ${asset} (unparseable)`);
    continue;
  }
  const body = m[1].replace(/\s+/g, ' ').trim();
  entries.push([name, body]);
}

if (missing.length) {
  console.error('Missing Phosphor assets:\n  ' + missing.join('\n  '));
  process.exit(1);
}

entries.sort((a, b) => a[0].localeCompare(b[0]));

const file = `/**
 * Local inline SVG icon set — Phosphor Icons, Bold weight.
 *
 * Generated by scripts/build-icons.mjs from @phosphor-icons/core; the paths are
 * inlined so the shipped bundle has no runtime dependency on the package. Every
 * glyph shares Phosphor's 256-unit grid, so any two icons line up at equal
 * size with no per-icon optical correction.
 *
 * Sizing: 24px reads as body/nav, 18px as inline, 16px inside buttons.
 */

const P = {
${entries.map(([n, b]) => `  ${n}: '${b.replace(/'/g, "\\'")}',`).join('\n')}
};

/**
 * @param {string} name  key of \`P\`
 * @param {number} size  rendered px on both axes
 * @returns {string}     inline <svg> markup
 */
export function icon(name, size = 18) {
  const d = P[name];
  if (!d) return '';
  return (
    \`<svg class="i" width="\${size}" height="\${size}" viewBox="0 0 256 256" fill="currentColor" \` +
    \`aria-hidden="true" focusable="false">\${d}</svg>\`
  );
}

export const icons = P;
`;

writeFileSync(out, file, 'utf8');
console.log(`Wrote ${entries.length} icons to ${out}`);
